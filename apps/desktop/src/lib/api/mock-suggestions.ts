import { childrenOf, type MockNode, type MockTree } from './mock-tree';
import type { NodeId, SuggestionDto, SuggestionsDto, Verdict } from './types';

/** The most nodes one suggestion lists, like the real backend. */
export const MAX_SUGGESTION_NODES = 20;

/** A folder the rules look at: where it is, and what sits next to it. */
interface Candidate {
  node: MockNode;
  /** Display path: the home directory is written `~`. */
  path: string;
  siblings: MockNode[];
}

interface Rule {
  id: string;
  title: string;
  verdict: Verdict;
  reason: (items: number) => string;
  matches: (candidate: Candidate) => boolean;
  /** The path or pattern shown for the suggestion, from the display paths of everything it matched. */
  label: (paths: string[]) => string;
}

const HOME = /^\/home\/[^/]+/;

const projects = (count: number): string => `${count} ${count === 1 ? 'project' : 'projects'}`;

/** A folder at a fixed display path, such as `/var/log/journal` or `~/Downloads`. */
function fixed(id: string, title: string, path: string, verdict: Verdict, reason: string): Rule {
  return {
    id,
    title,
    verdict,
    reason: () => reason,
    matches: (candidate) => candidate.path === path,
    label: () => path,
  };
}

/** A build or dependency folder with this name, next to the sources of a project. */
function nextToSources(id: string, title: string, name: string, reason: string): Rule {
  return {
    id,
    title,
    verdict: 'safe',
    reason: (items) => `${reason} Found in ${projects(items)}.`,
    matches: ({ node, siblings }) =>
      node.name === name && siblings.some((sibling) => sibling.name === 'src' && sibling.kind === 'dir'),
    label: (paths) => (paths.length === 1 ? (paths[0] as string) : `${commonParent(paths)}/**/${name}`),
  };
}

/** The deepest folder that holds all the paths. */
function commonParent(paths: string[]): string {
  const split = paths.map((path) => path.split('/').slice(0, -1));
  const first = split[0] ?? [];
  let length = first.length;

  for (const parts of split) {
    let shared = 0;

    while (shared < length && parts[shared] === first[shared]) {
      shared++;
    }

    length = shared;
  }

  return first.slice(0, length).join('/') || '/';
}

// Outermost wins, so a rule listed here never matches inside a folder another rule took.
const RULES: Rule[] = [
  fixed(
    'pacman-cache',
    'Pacman package cache',
    '/var/cache/pacman/pkg',
    'safe',
    'Old package versions. Pacman downloads them again when needed.',
  ),
  nextToSources('cargo-target', 'Rust build artifacts', 'target', 'Regenerated by cargo build.'),
  nextToSources('node-modules', 'node_modules', 'node_modules', 'Reinstallable from the lockfile.'),
  fixed(
    'user-cache',
    'Application caches',
    '~/.cache',
    'safe',
    'Browsers and tools rebuild these. Running apps are skipped.',
  ),
  fixed(
    'trash',
    'Trash',
    '~/.local/share/Trash',
    'safe',
    'Already deleted by you. Emptying it gives the space back.',
  ),
  fixed(
    'system-journal',
    'System journal',
    '/var/log/journal',
    'safe',
    'Old system logs. The most recent weeks are kept.',
  ),
  fixed(
    'docker-data',
    'Docker images and layers',
    '/var/lib/docker',
    'review',
    'Not used by any container. Volumes are untouched, but rebuilding images costs time.',
  ),
  fixed(
    'snapshots',
    'Old snapshots',
    '/.snapshots',
    'review',
    'Snapshots are rollback points. Deleting them removes those restore points.',
  ),
  fixed(
    'downloads',
    'Downloads',
    '~/Downloads',
    'review',
    'Personal files, so only you can tell whether you still need them.',
  ),
  fixed(
    'steam-library',
    'Steam library',
    '~/.local/share/Steam',
    'keep',
    'Your installed games. They are left alone.',
  ),
];

const VERDICT_ORDER: Record<Verdict, number> = { safe: 0, review: 1, keep: 2 };

interface Match {
  node: MockNode;
  path: string;
}

/** Walks the tree from the top. A folder some rule takes is not entered again, so no byte is counted twice. */
function collectMatches(tree: MockTree): Map<Rule, Match[]> {
  const matches = new Map<Rule, Match[]>(RULES.map((rule) => [rule, []]));
  const root = tree.nodes[0] as MockNode;
  const stack: Match[] = [{ node: root, path: tree.rootPath }];

  for (let current = stack.pop(); current; current = stack.pop()) {
    const children = childrenOf(tree, current.node);
    const prefix = current.path === '/' ? '' : current.path;

    for (const child of children) {
      // Mounts that were skipped and folders that could not be read are never suggested.
      if (child.kind !== 'dir' || child.unreadable) {
        continue;
      }

      const path = `${prefix}/${child.name}`;
      const candidate: Candidate = {
        node: child,
        path: path.replace(HOME, '~'),
        siblings: children,
      };
      const rule = RULES.find((entry) => entry.matches(candidate));

      if (rule && child.allocated > 0) {
        matches.get(rule)?.push({ node: child, path: candidate.path });
      } else {
        stack.push({ node: child, path });
      }
    }
  }

  return matches;
}

/** The mock's stand-in for `get_suggestions`: a small rule set over the demo tree. */
export function suggestionsOf(tree: MockTree): SuggestionsDto {
  const matches = collectMatches(tree);
  const suggestions: SuggestionDto[] = [];

  for (const rule of RULES) {
    const found = matches.get(rule) ?? [];

    if (found.length === 0) {
      continue;
    }

    const largest = found
      .map((match) => match.node)
      .sort((a, b) => b.allocated - a.allocated || a.id - b.id)
      .slice(0, MAX_SUGGESTION_NODES);

    suggestions.push({
      id: rule.id,
      title: rule.title,
      path: rule.label(found.map((match) => match.path)),
      verdict: rule.verdict,
      reason: rule.reason(found.length),
      allocated: found.reduce((sum, match) => sum + match.node.allocated, 0),
      items: found.length,
      nodes: largest.map((node): NodeId => node.id),
    });
  }

  suggestions.sort(
    (a, b) => VERDICT_ORDER[a.verdict] - VERDICT_ORDER[b.verdict] || b.allocated - a.allocated,
  );

  const totals = { safe: 0, review: 0, keep: 0 };

  for (const suggestion of suggestions) {
    totals[suggestion.verdict] += suggestion.allocated;
  }

  return { suggestions, totals };
}
